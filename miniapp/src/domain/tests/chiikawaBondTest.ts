function qo(text: string, picks: Array<[string, string]>): TestDefinition['questions'][number] {
  return { text, options: picks.map(([charText, reportId]) => ({ text: charText, reportId })) }
}

function q(text: string, texts: string[]): TestDefinition['questions'][number] {
  return {
    text,
    options: OPTION_NAMES.map(([reportId, theme], index) => ({ text: texts[index] ?? theme, reportId })),
  }
}

